-- Module: catalog

create table medical_items (
    price numeric(15,2) not null,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    updated_at timestamptz not null,
    public_id uuid not null unique,
    name varchar(200) not null,
    description text,
    instruction text,
    type varchar(255) not null check ((type in ('CLINICAL','LAB','IMAGING','VACCINATION','OTHER'))),
    primary key (id)
);

create table medical_services (
    duration_minutes integer not null,
    max_age integer,
    min_age integer,
    price numeric(15,2) not null,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    updated_at timestamptz not null,
    public_id uuid not null unique,
    name varchar(200) not null,
    description text,
    instruction text,
    target varchar(255) default 'BOTH' not null check ((target in ('MALE','FEMALE','BOTH'))),
    primary key (id)
);

create table medical_service_items (
    quantity integer default 1 not null,
    created_at timestamp(6) with time zone not null,
    item_id bigint not null,
    service_id bigint not null,
    primary key (item_id, service_id)
);

create table medical_packages (
    created_at timestamptz not null,
    id bigint generated by default as identity,
    updated_at timestamptz not null,
    public_id uuid not null unique,
    code varchar(40) not null unique,
    name varchar(200) not null,
    primary key (id)
);

create table package_specialities (
    created_at timestamp(6) with time zone not null,
    package_id bigint not null,
    specialty_id bigint not null,
    primary key (package_id, specialty_id)
);

create table package_versions (
    consultation_minutes integer not null,
    max_age integer,
    min_age integer,
    unit_price numeric(15,2) not null,
    created_at timestamp(6) with time zone not null,
    effective_from timestamp(6) with time zone not null,
    effective_to timestamp(6) with time zone,
    id bigint generated by default as identity,
    package_id bigint not null,
    version varchar(30) not null,
    code varchar(50) not null unique,
    name varchar(200) not null,
    class varchar(255) not null check ((class in ('STANDARD','ADVANCED','SPECIALIZED'))),
    description text,
    instruction text,
    status varchar(255) not null check ((status in ('OPENING','CLOSING','DISCOUNT'))),
    target varchar(255) default 'BOTH' not null check ((target in ('MALE','FEMALE','BOTH'))),
    primary key (id),
    constraint uk_package_versions_package_version unique (package_id, version)
);

create table package_version_items (
    position integer not null,
    quantity integer default 1 not null,
    item_id bigint not null,
    package_version_id bigint not null,
    item_name_snapshot varchar(200) not null,
    instruction_snapshot text,
    primary key (item_id, package_version_id)
);

alter table medical_service_items
  add constraint fk_medical_service_items_item_id
  foreign key (item_id) references medical_items (id);

alter table medical_service_items
  add constraint fk_medical_service_items_service_id
  foreign key (service_id) references medical_services (id);

alter table package_specialities
  add constraint fk_package_specialities_package_id
  foreign key (package_id) references medical_packages (id);

alter table package_versions
  add constraint fk_package_versions_package_id
  foreign key (package_id) references medical_packages (id);

alter table package_version_items
  add constraint fk_package_version_items_item_id
  foreign key (item_id) references medical_items (id);

alter table package_version_items
  add constraint fk_package_version_items_package_version_id
  foreign key (package_version_id) references package_versions (id);
