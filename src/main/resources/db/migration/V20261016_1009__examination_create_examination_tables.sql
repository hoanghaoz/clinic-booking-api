-- Module: examination

create table medical_visits (
    diastolic_bp integer,
    heart_rate integer,
    height_cm numeric(5,2),
    systolic_bp integer,
    temperature_c numeric(4,1),
    weight_kg numeric(5,2),
    appointment_id bigint not null unique,
    completed_at timestamptz,
    created_at timestamptz not null,
    followup_recommended_at timestamptz,
    id bigint generated by default as identity,
    patient_id bigint not null,
    prescribed_at timestamptz,
    prescribed_by_doctor_id bigint,
    primary_doctor_id bigint,
    received_at timestamptz not null,
    received_by_staff_id bigint not null,
    summary_issued_at timestamptz,
    updated_at timestamptz not null,
    public_id uuid not null unique,
    code varchar(40) not null unique,
    advice text,
    clinical_notes text,
    conclusion text,
    final_diagnosis text,
    initial_diagnosis text,
    prescription_status varchar(255) default 'DRAFT' not null check ((prescription_status in ('DRAFT','ISSUED','CANCELLED'))),
    status varchar(255) default 'WAITING' not null check ((status in ('WAITING','IN_PROGRESS','AWAITING_RESULTS','COMPLETED','CANCELLED'))),
    summary_status varchar(255) default 'DRAFT' not null check ((summary_status in ('DRAFT','ISSUED','CANCELLED'))),
    symptoms text,
    prescription jsonb,
    primary key (id)
);

create table medical_orders (
    occurrence_no integer default 1 not null,
    queue_number integer,
    unit_price_snapshot numeric(15,2) not null,
    completed_at timestamptz,
    id bigint generated by default as identity,
    item_id bigint not null,
    ordered_at timestamptz not null,
    ordered_by_doctor_id bigint,
    package_version_id bigint,
    performed_at timestamptz,
    performed_by_doctor_id bigint,
    performed_by_staff_id bigint,
    performed_visit_id bigint,
    queued_at timestamptz,
    released_at timestamptz,
    room_id bigint,
    service_id bigint,
    started_at timestamptz,
    verified_at timestamptz,
    verified_by_doctor_id bigint,
    verified_by_staff_id bigint,
    visit_id bigint not null,
    public_id uuid not null unique,
    code varchar(40) not null unique,
    item_name_snapshot varchar(200) not null,
    deferred_reason text,
    instruction_snapshot text,
    result_conclusion text,
    result_status varchar(255) check ((result_status in ('DRAFT','VERIFIED','RELEASED'))),
    result_text text,
    source varchar(255) not null check ((source in ('PACKAGE','SERVICE','ADDITIONAL'))),
    status varchar(255) default 'ORDERED' not null check ((status in ('ORDERED','WAITING','IN_PROGRESS','COMPLETED','DEFERRED','CANCELLED'))),
    result_files jsonb,
    result_values jsonb,
    primary key (id),
    constraint uq_medical_orders_visit_source_item_occurrence unique (visit_id, source, item_id, occurrence_no)
);

create index idx_medical_visits_patient_received on medical_visits (patient_id, received_at);

create index idx_medical_visits_doctor_status on medical_visits (primary_doctor_id, status);

create index idx_medical_orders_room_status_queued on medical_orders (room_id, status, queued_at);

create index idx_medical_orders_performed_visit on medical_orders (performed_visit_id);

alter table medical_orders
  add constraint fk_medical_orders_visit_id
  foreign key (visit_id) references medical_visits (id);
