-- Module: auth

create table users (
    created_at timestamptz not null,
    id bigint generated by default as identity,
    updated_at timestamptz not null,
    public_id uuid not null unique,
    username varchar(100) not null unique,
    email varchar(254) not null unique,
    password_hashed text not null,
    role varchar(255) not null check ((role in ('PATIENT','MEDICAL_STAFF','DOCTOR','ADMIN','COMPANY'))),
    status varchar(255) default 'ACTIVE' not null check ((status in ('ACTIVE','DISABLED'))),
    primary key (id)
);

create table refresh_tokens (
    created_at timestamptz not null,
    expires_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    revoked_at timestamp(6) with time zone,
    updated_at timestamptz not null,
    user_id bigint not null,
    token_hash varchar(128) not null unique,
    primary key (id)
);

create index idx_refresh_tokens_user_revoked on refresh_tokens (user_id, revoked_at);

create index idx_refresh_tokens_expires_at on refresh_tokens (expires_at);

alter table refresh_tokens
  add constraint fk_refresh_tokens_user_id
  foreign key (user_id) references users (id);
