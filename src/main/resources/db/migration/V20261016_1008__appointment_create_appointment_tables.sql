-- Module: appointment

create table appointments (
    deposit_required numeric(15,2) default 0 not null,
    price_snapshot numeric(15,2) not null,
    contract_member_id bigint,
    created_at timestamptz not null,
    created_by_staff_id bigint,
    end_at timestamptz not null,
    followup_visit_id bigint,
    hold_expires_at timestamptz,
    id bigint generated by default as identity,
    makeup_order_id bigint,
    package_version_id bigint,
    patient_id bigint not null,
    schedule_id bigint not null,
    service_id bigint,
    start_at timestamptz not null,
    updated_at timestamptz not null,
    public_id uuid not null unique,
    code varchar(40) not null unique,
    qr_token_hash varchar(128) unique,
    note text,
    preparation_snapshot text,
    source varchar(255) default 'ONLINE' not null check ((source in ('ONLINE','FRONT_DESK','PHONE','COMPANY'))),
    status varchar(255) default 'CONFIRMED' not null check ((status in ('HELD','CONFIRMED','CHECKED_IN','COMPLETED','CANCELLED','NO_SHOW','EXPIRED'))),
    cancellation_policy_snapshot jsonb not null,
    primary key (id)
);

create table appointment_slots (
    appointment_id bigint not null,
    released_at timestamptz,
    reserved_at timestamptz not null,
    slot_id bigint not null,
    primary key (appointment_id, slot_id)
);

create table appointment_histories (
    actor_patient_id bigint,
    actor_staff_id bigint,
    appointment_id bigint not null,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    new_end_at timestamptz,
    new_schedule_id bigint,
    new_start_at timestamptz,
    old_end_at timestamptz,
    old_schedule_id bigint,
    old_start_at timestamptz,
    action varchar(255) not null check ((action in ('CREATED','CONFIRMED','RESCHEDULED','CANCELLED','LATE_CANCELLED','CHECKED_IN','COMPLETED','NO_SHOW','EXPIRED'))),
    actor varchar(255) not null check ((actor in ('PATIENT','STAFF','SYSTEM'))),
    new_status varchar(255) check ((new_status in ('HELD','CONFIRMED','CHECKED_IN','COMPLETED','CANCELLED','NO_SHOW','EXPIRED'))),
    old_status varchar(255) check ((old_status in ('HELD','CONFIRMED','CHECKED_IN','COMPLETED','CANCELLED','NO_SHOW','EXPIRED'))),
    reason text,
    primary key (id)
);

create table appointment_waitlists (
    priority integer default 0 not null,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    notified_at timestamptz,
    offer_expires_at timestamptz,
    offered_appointment_id bigint unique,
    package_version_id bigint,
    patient_id bigint not null,
    requested_end_at timestamptz not null,
    requested_start_at timestamptz not null,
    schedule_id bigint not null,
    service_id bigint,
    updated_at timestamptz not null,
    status varchar(255) default 'WAITING' not null check ((status in ('WAITING','OFFERED','BOOKED','CANCELLED','EXPIRED'))),
    primary key (id)
);

create index idx_appointments_patient_start on appointments (patient_id, start_at);

create index idx_appointments_schedule_status on appointments (schedule_id, status);

create index idx_appointments_status_hold_expires on appointments (status, hold_expires_at);

create index idx_appointment_slots_slot on appointment_slots (slot_id);

create index idx_appointment_histories_appointment_created on appointment_histories (appointment_id, created_at);

create index idx_appointment_waitlists_queue on appointment_waitlists (schedule_id, status, priority, created_at);

alter table appointment_slots
  add constraint fk_appointment_slots_appointment_id
  foreign key (appointment_id) references appointments (id);

alter table appointment_histories
  add constraint fk_appointment_histories_appointment_id
  foreign key (appointment_id) references appointments (id);
