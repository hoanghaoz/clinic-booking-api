-- Module: company

create table companies (
    created_at timestamptz not null,
    id bigint generated by default as identity,
    updated_at timestamptz not null,
    public_id uuid not null unique,
    contact_phone varchar(25),
    tax_code varchar(30) not null unique,
    code varchar(40) not null unique,
    contact_name varchar(150),
    name varchar(200) not null,
    contact_email varchar(254),
    address text not null,
    status varchar(255) default 'ACTIVE' not null check ((status in ('ACTIVE','INACTIVE'))),
    primary key (id)
);

create table company_users (
    is_active boolean default true not null,
    company_id bigint not null,
    created_at timestamptz not null,
    user_id bigint not null,
    primary key (company_id, user_id)
);

create table corporate_contracts (
    booking_priority integer default 0 not null,
    ends_on date not null,
    starts_on date not null,
    company_id bigint not null,
    created_at timestamptz not null,
    created_by_user_id bigint not null,
    id bigint generated by default as identity,
    updated_at timestamptz not null,
    public_id uuid not null unique,
    code varchar(50) not null unique,
    note text,
    payment_terms text,
    status varchar(255) default 'DRAFT' not null check ((status in ('DRAFT','ACTIVE','COMPLETED','CANCELLED'))),
    primary key (id)
);

create table contract_packages (
    agreed_price numeric(15,2) not null,
    deposit_required numeric(15,2) default 0 not null,
    max_participants integer,
    contract_id bigint not null,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    package_version_id bigint not null,
    primary key (id),
    constraint uq_contract_packages_contract_version unique (contract_id, package_version_id)
);

create table contract_members (
    contract_package_id bigint not null,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    patient_id bigint not null,
    updated_at timestamptz not null,
    uploaded_by_user_id bigint not null,
    employee_code varchar(50) not null,
    status varchar(255) default 'ENROLLED' not null check ((status in ('ENROLLED','CANCELLED'))),
    primary key (id),
    constraint uq_contract_members_package_patient unique (contract_package_id, patient_id),
    constraint uq_contract_members_package_employee_code unique (contract_package_id, employee_code)
);

create index idx_company_users_user on company_users (user_id);

create index idx_corporate_contracts_company_status on corporate_contracts (company_id, status);

create index idx_contract_members_patient on contract_members (patient_id);

alter table company_users
  add constraint fk_company_users_company_id
  foreign key (company_id) references companies (id);

alter table corporate_contracts
  add constraint fk_corporate_contracts_company_id
  foreign key (company_id) references companies (id);

alter table contract_packages
  add constraint fk_contract_packages_contract_id
  foreign key (contract_id) references corporate_contracts (id);

alter table contract_members
  add constraint fk_contract_members_contract_package_id
  foreign key (contract_package_id) references contract_packages (id);
