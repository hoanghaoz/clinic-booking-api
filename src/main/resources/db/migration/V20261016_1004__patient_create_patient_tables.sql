-- Module: patient

create table patients (
    date_of_birth date not null,
    card_activated_at timestamp(6) with time zone,
    card_expires_at timestamp(6) with time zone,
    card_revoked_at timestamp(6) with time zone,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    updated_at timestamptz not null,
    user_id bigint unique,
    public_id uuid not null unique,
    gender varchar(20) not null check ((gender in ('MALE','FEMALE'))),
    identity_type varchar(20) not null,
    phone varchar(25) not null,
    card_number varchar(40) unique,
    identity_number varchar(40) not null,
    identity_issuer varchar(80) not null,
    full_name varchar(150) not null,
    contact_email varchar(254),
    address text not null,
    class varchar(255) default 'PERSONAL' not null check ((class in ('NORMAL','VIP','PERSONAL','COMPANY'))),
    primary key (id),
    constraint uk_patients_identity unique (identity_type, identity_issuer, identity_number)
);

create table patient_medical_histories (
    id bigint generated by default as identity,
    patient_id bigint not null,
    recorded_at timestamp(6) with time zone not null,
    recorded_by_doctor_id bigint,
    recorded_by_staff_id bigint,
    updated_at timestamp(6) with time zone not null,
    family_relationship varchar(50),
    description text not null,
    type varchar(255) not null check ((type in ('PERSONAL','FAMILY','ALLERGY'))),
    primary key (id)
);

create index idx_patients_phone on patients (phone);

create index idx_patient_medical_histories_patient_type on patient_medical_histories (patient_id, type);

alter table patient_medical_histories
  add constraint fk_patient_medical_histories_patient_id
  foreign key (patient_id) references patients (id);
