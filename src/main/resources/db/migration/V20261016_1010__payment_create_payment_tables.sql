-- Module: payment

create table invoices (
    discount_amount numeric(15,2) default 0 not null,
    subtotal numeric(15,2) not null,
    total_amount numeric(15,2) not null,
    appointment_id bigint not null,
    company_id bigint,
    contract_id bigint,
    created_at timestamptz not null,
    created_by_staff_id bigint,
    id bigint generated by default as identity,
    issued_at timestamptz,
    updated_at timestamptz not null,
    voided_at timestamptz,
    public_id uuid not null unique,
    buyer_tax_code_snapshot varchar(30),
    code varchar(50) not null unique,
    buyer_name_snapshot varchar(200) not null,
    buyer_address_snapshot text,
    payer varchar(255) default 'PATIENT' not null check ((payer in ('PATIENT','COMPANY'))),
    status varchar(255) default 'DRAFT' not null check ((status in ('DRAFT','ISSUED','VOID'))),
    void_reason text,
    primary key (id)
);

create table invoice_items (
    discount_amount numeric(15,2) default 0 not null,
    line_total numeric(15,2) not null,
    quantity numeric(10,2) default 1 not null,
    unit_price numeric(15,2) not null,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    invoice_id bigint not null,
    medical_order_id bigint,
    voided_at timestamptz,
    charge_key varchar(150) not null,
    description_snapshot text not null,
    type varchar(255) not null check ((type in ('BASE_FEE','ADDITIONAL','CANCELLATION_FEE'))),
    primary key (id)
);

create table payments (
    amount numeric(15,2) not null,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    invoice_id bigint not null,
    paid_at timestamptz,
    received_by_staff_id bigint,
    public_id uuid not null unique,
    receipt_code varchar(50) not null unique,
    provider varchar(80),
    idempotency_key varchar(150) not null unique,
    provider_reference varchar(150),
    kind varchar(255) not null check ((kind in ('DEPOSIT','SETTLEMENT'))),
    method varchar(255) not null check ((method in ('CASH','BANK_CARD','BANK_TRANSFER','PRIVATE_INSURANCE','COMPANY_TRANSFER'))),
    status varchar(255) default 'PENDING' not null check ((status in ('PENDING','SUCCEEDED','FAILED','CANCELLED'))),
    primary key (id),
    constraint uq_payments_provider_reference unique (provider, provider_reference)
);

create table refunds (
    amount numeric(15,2) not null,
    cancellation_history_id bigint,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    payment_id bigint not null,
    processed_by_staff_id bigint,
    refunded_at timestamptz,
    public_id uuid not null unique,
    code varchar(50) not null unique,
    provider varchar(80),
    idempotency_key varchar(150) not null unique,
    provider_reference varchar(150),
    description text,
    reason varchar(255) not null check ((reason in ('EARLY_CANCELLATION','SERVICE_CANCELLATION','OVERPAYMENT','OTHER'))),
    status varchar(255) default 'PENDING' not null check ((status in ('PENDING','SUCCEEDED','FAILED','CANCELLED'))),
    primary key (id),
    constraint uq_refunds_provider_reference unique (provider, provider_reference)
);

create index idx_invoices_appointment_status on invoices (appointment_id, status);

create index idx_invoice_items_invoice on invoice_items (invoice_id);

create index idx_invoice_items_medical_order on invoice_items (medical_order_id);

create index idx_invoice_items_charge_key on invoice_items (charge_key);

create index idx_payments_invoice_status on payments (invoice_id, status);

create index idx_refunds_payment_status on refunds (payment_id, status);

alter table invoice_items
  add constraint fk_invoice_items_invoice_id
  foreign key (invoice_id) references invoices (id);

alter table payments
  add constraint fk_payments_invoice_id
  foreign key (invoice_id) references invoices (id);

alter table refunds
  add constraint fk_refunds_payment_id
  foreign key (payment_id) references payments (id);
