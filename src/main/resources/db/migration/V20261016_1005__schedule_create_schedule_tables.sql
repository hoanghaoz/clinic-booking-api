-- Module: schedule

create table shifts (
    end_time time(0) not null,
    start_time time(0) not null,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    updated_at timestamptz not null,
    code varchar(30) not null unique,
    name varchar(100) not null,
    primary key (id)
);

create table doctor_schedules (
    work_date date not null,
    created_at timestamptz not null,
    doctor_id bigint not null,
    end_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    room_id bigint not null,
    shift_id bigint not null,
    specialty_id bigint not null,
    start_at timestamp(6) with time zone not null,
    updated_at timestamptz not null,
    public_id uuid not null unique,
    status varchar(255) default 'OPEN' not null check ((status in ('OPEN','CLOSED','CANCELLED'))),
    primary key (id),
    constraint uk_doctor_schedules_doctor_date_shift unique (doctor_id, work_date, shift_id),
    constraint uk_doctor_schedules_room_date_shift unique (room_id, work_date, shift_id)
);

create table doctor_schedule_slots (
    created_at timestamptz not null,
    end_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    schedule_id bigint not null,
    start_at timestamp(6) with time zone not null,
    updated_at timestamptz not null,
    status varchar(255) default 'AVAILABLE' not null check ((status in ('AVAILABLE','BLOCKED'))),
    primary key (id),
    constraint uk_doctor_schedule_slots_schedule_start unique (schedule_id, start_at)
);

create index idx_doctor_schedules_work_date_status on doctor_schedules (work_date, status);

alter table doctor_schedules
  add constraint fk_doctor_schedules_shift_id
  foreign key (shift_id) references shifts (id);

alter table doctor_schedule_slots
  add constraint fk_doctor_schedule_slots_schedule_id
  foreign key (schedule_id) references doctor_schedules (id);
