-- Module: violation

create table patient_violations (
    occurrence_count_snapshot integer,
    appointment_id bigint not null,
    booking_restricted_from timestamptz,
    booking_restricted_until timestamptz,
    created_at timestamptz not null,
    id bigint generated by default as identity,
    medical_order_id bigint,
    occurred_at timestamptz not null,
    patient_id bigint not null,
    recorded_by_staff_id bigint,
    revoked_at timestamptz,
    updated_at timestamptz not null,
    public_id uuid not null unique,
    code varchar(50) not null unique,
    description text not null,
    revoke_reason text,
    type varchar(255) not null check ((type in ('NO_SHOW','LATE_CANCELLATION','PREPARATION_NOT_FOLLOWED'))),
    primary key (id)
);

create index idx_patient_violations_patient_type_occurred on patient_violations (patient_id, type, occurred_at);

create index idx_patient_violations_patient_restricted_until on patient_violations (patient_id, booking_restricted_until);
