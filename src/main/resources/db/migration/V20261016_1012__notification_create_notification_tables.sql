-- Module: notification

create table notifications (
    attempt_count integer default 0 not null,
    max_attempts integer default 5 not null,
    appointment_id bigint,
    created_at timestamptz not null,
    created_by_user_id bigint,
    id bigint generated by default as identity,
    invoice_id bigint,
    locked_until timestamptz,
    medical_visit_id bigint,
    next_attempt_at timestamptz not null,
    patient_id bigint,
    read_at timestamptz,
    scheduled_at timestamptz not null,
    sent_at timestamptz,
    updated_at timestamptz not null,
    user_id bigint,
    waitlist_id bigint,
    public_id uuid not null unique,
    deduplication_key varchar(200) not null unique,
    title varchar(200) not null,
    recipient_email varchar(254),
    channel varchar(255) not null check ((channel in ('IN_APP','EMAIL'))),
    content text not null,
    last_error text,
    status varchar(255) default 'PENDING' not null check ((status in ('PENDING','PROCESSING','SENT','FAILED','CANCELLED'))),
    type varchar(255) not null check ((type in ('APPOINTMENT_CONFIRMED','APPOINTMENT_REMINDER','APPOINTMENT_RESCHEDULED','APPOINTMENT_CANCELLED','WAITLIST_OFFER','CARD_EXPIRING','CARD_EXPIRED','MEDICAL_RESULT_READY','PRESCRIPTION_READY','PAYMENT_SUCCEEDED','REFUND_SUCCEEDED','BOOKING_RESTRICTED','BOOKING_RESTRICTION_REVOKED','COMPANY_IMPORT_COMPLETED','SYSTEM'))),
    data jsonb,
    primary key (id)
);

create index idx_notifications_user_channel_read_created on notifications (user_id, channel, read_at, created_at);

create index idx_notifications_status_next_attempt on notifications (status, next_attempt_at);

create index idx_notifications_patient_type_status on notifications (patient_id, type, status);

create index idx_notifications_appointment on notifications (appointment_id);
